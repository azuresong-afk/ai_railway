-- Просмотр журнала аудита в консоли (ревью 2.r3b этапа 2, В17).
--
-- Выборка идёт двумя частями UNION ALL: период по индексу audit_log_ts и
-- записи с не конечным временем. Таких записей нет (CHECK (isfinite(ts))),
-- они появляются только при подмене в обход продукта; просмотр показывает
-- их в любом периоде. Частичный индекс обычно пуст и делает эту часть
-- выборки дешёвой даже на журнале в десятки гигабайт.

CREATE INDEX audit_log_not_finite ON audit_log (org_id, seq) WHERE NOT isfinite(ts);
