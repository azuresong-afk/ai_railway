-- Необязательный e-mail учётной записи (решение владельца по пилоту,
-- задача 4.6 этапа 4): адрес для рассылки отчётов по расписанию. Пустая
-- строка — адреса нет. Проверка формата — в приложении (internal/auth);
-- здесь только предел длины. Адрес — персональные данные: в технические
-- журналы не пишется, в журнал аудита — только факт изменения.
ALTER TABLE users ADD COLUMN email text NOT NULL DEFAULT '' CHECK (char_length(email) <= 254);

-- Менять адрес может только сервер (приложение); остальные столбцы — как прежде.
GRANT UPDATE (email) ON users TO aisec_app;
