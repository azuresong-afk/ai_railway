-- Момент последнего получения ключей IdP для проверки JWT пользователей
-- приложений (4Н14 ревью 4.r2 этапа 4, задача 4.21, ADR-0025, раздел 4).
--
-- Если IdP недоступен, сервер кладёт в пакет ключи прежней версии, но не
-- дольше 24 ч от последнего успешного получения. Раньше этот момент жил
-- только в памяти и отсчитывался заново от запуска сервера: при
-- перезапусках чаще раза в сутки ключ, отозванный у IdP, оставался в пакете
-- бессрочно. Формат пакета не меняется (шлюз разбирает его строго): момент
-- хранится на сервере. Одна строка на организацию, только последнее
-- значение; без содержимого ключей.

CREATE TABLE user_token_keys_state (
    org_id     uuid        PRIMARY KEY REFERENCES organizations (id),
    fetched_at timestamptz NOT NULL
);

REVOKE ALL ON user_token_keys_state FROM PUBLIC;
GRANT SELECT, INSERT, UPDATE ON user_token_keys_state TO aisec_app;
