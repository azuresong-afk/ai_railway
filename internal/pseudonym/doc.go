// Пакет pseudonym — псевдонимизация фрагментов запроса к модели и обратная
// подстановка значений в ответ (ТЗ, 5.1 «Псевдонимизация с обратной
// подстановкой», 5.3; DM-31).
//
// Vault — словарь «значение ↔ псевдоним» одного запроса. Живёт только в
// памяти на время запроса, нигде не сохраняется и не попадает в логи:
// String и LogValue печатают только число записей. Псевдоним — [[ТИП_N]]
// (ADR-0005): ТИП — категория находки латиницей (PHONE, SNILS), N — номер
// значения этого типа в запросе. Одинаковые значения получают один псевдоним.
// Маскирование (redact) необратимо и даёт [[ТИП]] без номера.
//
// Обратная подстановка принимает частые искажения, которые вносит модель
// (экранирование markdown, регистр, пробелы, одна скобка вместо двух), но
// возвращает только значения из словаря этого запроса. Псевдоним, который
// не удалось сопоставить, остаётся в ответе как есть — значение остаётся
// замаскированным, а случай считается в метрике неудачных подстановок.
// Псевдоним внутри адреса (после «//» без пробела) не восстанавливается:
// иначе инъекция заставит модель вставить его в ссылку на чужой сервер, и
// приложение само отправит туда значение (DM-11, docs/cert/threat-model.md).
//
// Подключение к конвейеру шлюза — задача 1.23.
